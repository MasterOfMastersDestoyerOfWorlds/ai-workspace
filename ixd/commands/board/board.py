"""Open the ticket board in the browser, rendered from the live ticket store."""

import re
import webbrowser

from ... import worktree
from ..review import _desktop as desktop
from ..review import _page as page_style
from ...registry import cli_command

HEADING = re.compile(r"^(#{1,3}) (.*)$")
TICKET_LINK = re.compile(r"\[([A-Z]+-\d+)\]\(([^)]+)\)")
BOLD = re.compile(r"\*\*(.+?)\*\*")
STRUCK = re.compile(r"~~(.+?)~~")
ITALIC = re.compile(r"^\*(.+)\*$")
DETAILS = re.compile(r"^<details><summary>(.*)</summary>$")

STYLE = """
h2 { font-size:20px; text-transform:none; letter-spacing:0; color:var(--fg); margin:28px 0 6px; }
h3 { color:var(--muted); }
ul { list-style:none; padding-left:0; }
li { padding:3px 0; border-bottom:1px solid var(--line); }
li .desc { color:var(--muted); }
details { margin:8px 0; }
hr { border:0; border-top:1px solid var(--line); margin:20px 0; }
"""


def inline(text):
    """One line's markdown spans as HTML: the ticket id as a link into VS Code, bold, struck text
    and the description, dimmed. BOARD.md repeats the id in bold after its link; the copy goes.
    """
    title, separator, description = text.partition(" -- ")
    rendered = page_style.e(title)
    rendered = TICKET_LINK.sub(
        lambda match: f'<a href="{page_style.vscode_link(worktree.TICKET_REPO / match.group(2))}">'
        f"<strong>{match.group(1)}</strong></a>",
        re.sub(r"(\[([A-Z]+-\d+)\]\([^)]+\)) \*\*\2\*\*", r"\1", rendered),
    )
    if separator:
        rendered += f' <span class="desc">&mdash; {page_style.e(description)}</span>'
    return STRUCK.sub(r"<s>\1</s>", BOLD.sub(r"<strong>\1</strong>", rendered))


def render(markdown):
    """BOARD.md as one self-contained HTML page.

    BOARD.md is generated by ``generate_board.py`` in a fixed shape, so only that shape is read:
    headings, ticket list items, the italic banner, rules and the Done/Archived ``<details>``.

    :param markdown: the board's text
    :return: the page
    """
    body = []
    in_list = False
    for line in markdown.splitlines():
        is_item = line.startswith("- ")
        if in_list and not is_item:
            body.append("</ul>")
            in_list = False
        heading = HEADING.match(line)
        details = DETAILS.match(line)
        italic = ITALIC.match(line)
        if is_item:
            if not in_list:
                body.append("<ul>")
                in_list = True
            body.append(f"<li>{inline(line[2:])}</li>")
        elif heading:
            level = len(heading.group(1))
            body.append(f"<h{level}>{page_style.e(heading.group(2))}</h{level}>")
        elif details:
            body.append(f"<details><summary>{page_style.e(details.group(1))}</summary>")
        elif line == "</details>":
            body.append("</details>")
        elif line == "---":
            body.append("<hr>")
        elif italic:
            body.append(f'<p class="muted">{page_style.e(italic.group(1))}</p>')
    if in_list:
        body.append("</ul>")
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>Ticket Board</title><style>{page_style.STYLE}{STYLE}</style></head>"
        f"<body><main>{''.join(body)}</main></body></html>"
    )


@cli_command
def board(page_only: bool = False) -> int:
    """Regenerate BOARD.md from the ticket store and open it in the browser as a page.

    The page is ``~/.cache/ixd/board.html``, rendered from the BOARD.md that
    ``generate_board.py board`` has just written, so it shows the live ticket store, unpushed
    changes included. Each ticket id opens the ticket's JSON in VS Code. Under Hyprland the page
    opens in a browser window of its own on the first empty workspace right of every workspace in
    use, and the view switches to it.

    :param page_only: write the page and print its path; open no browser
    """
    if not worktree.ticket_command("board", after="nothing changed yet"):
        return 1
    page = page_style.page_path("board").parent.parent / "board.html"
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text(render((worktree.TICKET_REPO / "BOARD.md").read_text(encoding="utf-8")), encoding="utf-8")
    print(f"== page: {page}")
    if page_only:
        return 0
    if desktop.available():
        workspace, _ = desktop.free_pair()
        if desktop.open_page(page.as_uri(), workspace) == "placed":
            desktop.show(workspace)
            print(f"== page: on workspace {workspace}")
            return 0
    webbrowser.open(page.as_uri())
    print("== page: opened in the browser")
    return 0
